import assert from 'node:assert/strict';
import {trackCover,trackSeed} from '../public/track-cover.js';
import {colorPalettes} from '../public/palettes.js';
const svg=trackCover('Quiet water','River');
assert.equal(svg,trackCover('Quiet water','River'));
assert.notEqual(svg,trackCover('Other water','River'));
assert.notEqual(svg,trackCover('Quiet water','Other artist'));
assert.notEqual(trackSeed('ab','c'),trackSeed('a','bc'));
assert.equal(trackCover(' Café ','River'),trackCover('Cafe\u0301','River'));
assert(!trackCover('<script>alert(1)</script>','" onload="evil()').includes('script'));
assert(!svg.includes('NaN'));
assert.match(svg, /<linearGradient/);
const allowed=new Set(['#202339','#eadfcf',...Object.values(colorPalettes).flatMap(p=>p.colors.map(c=>c.hex))]);
const families=new Map(),palettes=new Set(),covers=new Set();
for(let i=0;i<300;i++){
 const cover=trackCover('Song '+i,'Artist');
 assert.equal(cover,trackCover('Song '+i,'Artist'));
 assert(!/NaN|Infinity|undefined|<script|<image|<foreignObject|onload=/.test(cover));
 assert(cover.length<55000,'Artwork must remain lightweight');
 const family=cover.match(/data-family="([^"]+)"/)[1];
 assert(['ribbons','contours','modular'].includes(family));
 families.set(family,(families.get(family)||0)+1);
 palettes.add(cover.match(/data-palette="([^"]+)"/)[1]);
 const ids=[...cover.matchAll(/id="([^"]+)"/g)].map(m=>m[1]);
 assert.equal(new Set(ids).size,ids.length);
 for(const id of ids)assert.match(id,/^flow-cover-\d+-gradient$/);
 for(const [,ref] of cover.matchAll(/url\(#([^)]*)\)/g))assert(ids.includes(ref));
 for(const color of cover.match(/#[a-f0-9]{6}/g))assert(allowed.has(color));
 if(family==='ribbons')assert.match(cover,/stroke-linecap="round"/);
 if(family==='contours')assert.match(cover,/fill-opacity=".12"/);
 if(family==='modular')assert.match(cover,/transform="translate\(/);
 covers.add(cover);
}
assert.equal(covers.size,300);
assert.equal(palettes.size,8,'All Flow palettes should be represented');
for(const family of ['ribbons','contours','modular'])assert(families.get(family)>=65,'Families should be well distributed');
console.log('PASS: stable, distinct, safe Flow collection covers; three composition families, eight palettes, bounded output size.');
